USE ROLE SYSADMIN;
USE DATABASE SANDBOX;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA CONSUMPTION_SCH;
CREATE OR REPLACE DYNAMIC TABLE MY_DYNAMIC_TABLE (PRE_TAX_PROFIT, TAXES, AFTER_TAX_PROFIT) 
TARGET_LAG = '20 MINUTES' 
INITIALIZE = ON_CREAE
WAREHOUSE = MYWH 
AS
SELECT D.YEAR AS YEAR,
    -- FETCH YEAR FROM DATE_DIM
    D.MONTH AS MONTH,
    -- FETCH MONTH FROM DATE_DIM
    SUM(FACT.SUBTOTAL) AS TOTAL_REVENUE,
    COUNT(DISTINCT FACT.ORDER_ID) AS TOTAL_ORDERS,
    ROUND(
        SUM(FACT.SUBTOTAL) / COUNT(DISTINCT FACT.ORDER_ID),
        2
    ) AS AVG_REVENUE_PER_ORDER,
    ROUND(
        SUM(FACT.SUBTOTAL) / COUNT(FACT.ORDER_ITEM_ID),
        2
    ) AS AVG_REVENUE_PER_ITEM,
    MAX(FACT.SUBTOTAL) AS MAX_ORDER_VALUE
FROM CONSUMPTION_SCH.ORDER_ITEM_FACT FACT
    JOIN CONSUMPTION_SCH.DATE_DIM D ON FACT.ORDER_DATE_DIM_KEY = D.DATE_DIM_HK -- JOIN FACT TABLE WITH DATE_DIM TABLE
WHERE DELIVERY_STATUS = 'DELIVERED'
GROUP BY D.YEAR,
    D.MONTH
ORDER BY D.YEAR,
    D.MONTH;